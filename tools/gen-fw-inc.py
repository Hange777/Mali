#!/usr/bin/env python3
"""mali_csffw.bin -> mali_csffw.inc (a C initialiser list), so the kernel carries the Mali-G610 CSF firmware.

    tools/gen-fw-inc.py [mali_csffw.bin]

The input is the Arm Mali CSF firmware for the G610 (CSF binary header 0.3, 274432 bytes, sha256
8e7c821a55ca1c345cc79f61243616dd25fc35b81f090946f302886d67712df5; the interface version is read from the
shared section at boot). Pass the path or set MALI_CSFFW. The firmware is a vendor binary: neither the .bin
nor the generated .inc is committed (see .gitignore). The .inc is generated, never edited."""
import hashlib, os, sys

EXPECTED = '8e7c821a55ca1c345cc79f61243616dd25fc35b81f090946f302886d67712df5'
src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('MALI_CSFFW')
if not src:
    sys.exit('usage: gen-fw-inc.py mali_csffw.bin   (or set MALI_CSFFW)')
data = open(src, 'rb').read()
digest = hashlib.sha256(data).hexdigest()
if digest != EXPECTED:
    print('warning: sha256 %s differs from the tested firmware %s' % (digest, EXPECTED), file=sys.stderr)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'mali_csffw.inc')
with open(out, 'w') as f:
    f.write('// Generated by tools/gen-fw-inc.py from %s (%d bytes, sha256 %s). Do not edit.\n' % (os.path.basename(src), len(data), digest))
    for i in range(0, len(data), 32):
        f.write(','.join('0x%02x' % b for b in data[i:i + 32]) + ',\n')
print(os.path.normpath(out), len(data))
